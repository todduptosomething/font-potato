#!/bin/sh
# wawoff2's Emscripten binding only does `module["exports"] = Module` inside its
# ENVIRONMENT_IS_NODE branch, so in a browser it happily instantiates the wasm
# and then never hands the Module object to anyone. It opens with
#   var Module = typeof Module !== "undefined" ? Module : {};
# so declaring Module ourselves first makes it adopt OUR object, which we can
# then export. No bundler, no eval — just a prologue and an epilogue.
SRC=node_modules/wawoff2/build/compress_binding.js
OUT=public/engine/vendor-woff2.mjs
{
  echo '// GENERATED by build/make-woff2-esm.sh — do not edit.'
  echo 'var Module = {};'
  cat "$SRC"
  echo ''
  echo 'export default Module;'
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
